/**
 * The storage adapter interface.
 *
 * ── Why an abstraction ──────────────────────────────────────────────────
 *
 * The MVP writes uploads to the local filesystem, but the interface exists
 * so the driver can be swapped for S3, Cloudflare R2 or a private bucket
 * without touching a single call site. The important consequence of that
 * design rule is this one:
 *
 *   **Storage keys are persisted, not URLs.**
 *
 * `Product.images` and `AdvisorImage.storageKey` hold keys like
 * `advisor/2026/10/ab12….webp`. The URL is derived at render time via
 * `getUrl()`. If a URL were stored instead, moving to another driver would
 * mean rewriting every row.
 *
 * The interface is deliberately narrow — four operations, no streaming, no
 * multipart, no ACLs. The MVP does not need them, and a wide interface is
 * harder to implement for every future driver.
 */

/**
 * The result of storing a file.
 */
export type StoredObject = {
  /**
   * The storage key. Relative, slash-separated, and never derived from
   * user input.
   *
   * Example: `advisor/2026/10/9f2c1a7b4e5d6c8a0b1c2d3e4f5a6b7c.webp`
   */
  readonly key: string;
  /** The size in bytes of what was written. */
  readonly byteSize: number;
  /** The MIME type, detected server-side from magic bytes. */
  readonly mimeType: string;
};

/**
 * The input to `put`.
 */
export type PutInput = {
  /** The raw bytes to write. */
  readonly bytes: Buffer;
  /**
   * The MIME type, already **detected** from the file's magic bytes.
   *
   * The caller must not pass a client-declared type here. Validation
   * happens in `src/lib/upload/validate.ts` before the adapter is reached.
   */
  readonly mimeType: string;
  /**
   * The original filename.
   *
   * Used only for diagnostics. The stored filename is generated, never
   * derived from this value.
   */
  readonly originalName: string;
  /**
   * The namespace the object is stored under — e.g. `advisor`, `products`,
   * `reviews`.
   *
   * The scope is a fixed allow-list in the driver, not free text.
   */
  readonly scope: string;
};

/**
 * The storage interface.
 */
export interface StorageAdapter {
  /**
   * Writes an object and returns its key.
   *
   * The key is generated by the driver: `<scope>/<yyyy>/<mm>/<random>.<ext>`.
   * No segment of it comes from user input.
   */
  put(input: PutInput): Promise<StoredObject>;

  /**
   * Deletes an object.
   *
   * **Must be idempotent.** The cleanup job calls it repeatedly for keys
   * it has already tried to remove, and an already-absent file is a
   * success, not an error.
   */
  delete(key: string): Promise<void>;

  /**
   * Returns the public URL for a key.
   */
  getUrl(key: string): string;

  /**
   * Returns true when the object exists.
   */
  exists(key: string): Promise<boolean>;
}

/**
 * The scopes the local driver accepts.
 *
 * A fixed allow-list rather than free text: the scope becomes a directory
 * name, so accepting arbitrary strings would be the first half of a path
 * traversal attack. The driver rejects anything not in this list.
 *
 * The three discovery scopes — `categories`, `concerns` and `brands` —
 * back the storefront's "Shop By Category", "Shop By Skin Concern" and
 * "Shop By Brand" sections. They are separate directories because the
 * three are managed independently: a brand's logo is replaced far more
 * often than a category's card image, and one scope's cleanup job must
 * not sweep another's files.
 *
 * The `hero` scope holds the homepage carousel's banner artwork. It is
 * its own scope for the same reason: a campaign's artwork is the most
 * frequently replaced file in the shop — campaigns turn over — and it
 * must not be swept by a cleanup job that is collecting the discovery
 * sections' orphans.
 */
export const STORAGE_SCOPES = [
  "advisor",
  "products",
  "reviews",
  "profiles",
  "categories",
  "concerns",
  "brands",
  "hero",
] as const;

export type StorageScope = (typeof STORAGE_SCOPES)[number];

/**
 * Returns true when a string is a known storage scope.
 */
export function isStorageScope(value: string): value is StorageScope {
  return (STORAGE_SCOPES as readonly string[]).includes(value);
}

/**
 * The error thrown by a storage driver for an invalid request.
 *
 * A dedicated class so the route layer can turn it into a 4xx without
 * inspecting error messages.
 */
export class StorageError extends Error {
  readonly code:
    | "INVALID_SCOPE"
    | "INVALID_KEY"
    | "UNSUPPORTED_MIME_TYPE"
    | "WRITE_FAILED"
    | "READ_FAILED";

  constructor(
    code: StorageError["code"],
    message: string,
    cause?: unknown,
  ) {
    super(message);
    this.name = "StorageError";
    this.code = code;
    if (cause !== undefined) {
      this.cause = cause;
    }
  }
}
